import fs from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { NodeServices } from "@effect/platform-node";
import { Effect } from "effect";
import { afterEach, beforeEach, describe, expect, it } from "vite-plus/test";
import { runSeed, seedBanner } from "./run.js";
import type { SeedOverrides } from "./run.js";

const SCHEMA = `import { relations } from "drizzle-orm";
import { integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

export const user = sqliteTable("users", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  email: text("email").notNull().unique(),
  name: text("name").notNull(),
  isAdmin: integer("is_admin", { mode: "boolean" }).notNull().default(false),
  joinedAt: integer("joined_at", { mode: "timestamp" }).notNull(),
});

export const post = sqliteTable("posts", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  authorId: integer("author_id").notNull().references(() => user.id),
  title: text("title").notNull(),
});

export const userRelations = relations(user, ({ many }) => ({ posts: many(post) }));
export const postRelations = relations(post, ({ one }) => ({
  author: one(user, { fields: [post.authorId], references: [user.id] }),
}));
`;

// The config is a plain object here: \`defineConfig\` only types it, and the test does not build
// the package for \`import { defineConfig } from "sizuku"\` to resolve.
const CONFIG = `import * as schema from "./schema";

export default {
  schema,
  seed: 1,
  url: "file:./dev.db",
  models: {
    user: {
      data: [{ email: "ann@example.com", name: "Ann", joinedAt: "2025-01-02T03:04:05.000Z", posts: [{ title: "Hello" }] }],
    },
    post: { count: 3 },
  },
};
`;

const DDL = `
  CREATE TABLE users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    email TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    is_admin INTEGER NOT NULL DEFAULT 0,
    joined_at INTEGER NOT NULL
  );
  CREATE TABLE posts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    author_id INTEGER NOT NULL REFERENCES users(id),
    title TEXT NOT NULL
  );
`;

const NONE: SeedOverrides = {
  config: null,
  url: null,
  output: null,
  seed: null,
  count: null,
  locale: null,
  reset: false,
};

// node:sqlite gives rows without a prototype, so they are compared by value with toEqual.
function seed(dir: string, overrides: Partial<SeedOverrides> = {}) {
  return Effect.runPromise(
    runSeed({ ...NONE, ...overrides }, dir).pipe(Effect.provide(NodeServices.layer)),
  );
}

describe("runSeed", () => {
  let dir: string;

  beforeEach(() => {
    // Inside the package, so the schema's `drizzle-orm` import resolves.
    dir = fs.mkdtempSync(path.join(import.meta.dirname, ".seed-test-"));
    fs.writeFileSync(path.join(dir, "schema.ts"), SCHEMA);
    fs.writeFileSync(path.join(dir, "sizuku.config.ts"), CONFIG);
    const db = new DatabaseSync(path.join(dir, "dev.db"));
    db.exec(DDL);
    db.close();
  });

  afterEach(() => {
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("inserts the rows the config describes into the database of its url", async () => {
    const report = await seed(dir);
    expect(report.tables).toStrictEqual([
      { name: "user", table: "users", rows: 1 },
      { name: "post", table: "posts", rows: 4 },
    ]);
    expect(seedBanner(report)).toContain("💧 Seeded 5 rows (seed 1, locale en)");
    const db = new DatabaseSync(path.join(dir, "dev.db"));
    expect(db.prepare("SELECT id, email, name, is_admin, joined_at FROM users").all()).toEqual([
      {
        id: 1,
        email: "ann@example.com",
        name: "Ann",
        is_admin: 0,
        joined_at: Math.floor(Date.parse("2025-01-02T03:04:05.000Z") / 1000),
      },
    ]);
    expect(db.prepare("SELECT author_id, title FROM posts WHERE id = 1").get()).toEqual({
      author_id: 1,
      title: "Hello",
    });
    expect(db.prepare("SELECT COUNT(*) AS n FROM posts WHERE author_id = 1").get()).toEqual({
      n: 4,
    });
    db.close();
  });

  it("refuses to insert twice without --reset, and starts over with it", async () => {
    await seed(dir);
    await expect(seed(dir)).rejects.toThrow(/pass --reset/u);
    await seed(dir, { reset: true });
    const db = new DatabaseSync(path.join(dir, "dev.db"));
    expect(db.prepare("SELECT COUNT(*) AS n FROM users").get()).toEqual({ n: 1 });
    db.close();
  });

  it("writes the rows as a SQL script with --sql", async () => {
    const report = await seed(dir, { output: "seed.sql" });
    expect(report.target).toStrictEqual({ kind: "sql", path: path.join(dir, "seed.sql") });
    const sql = fs.readFileSync(path.join(dir, "seed.sql"), "utf-8");
    expect(sql).toContain("-- Generated by sizuku seed (seed 1, locale en)");
    expect(sql).toContain(
      `INSERT INTO "users" ("id", "email", "name", "is_admin", "joined_at") VALUES\n  (1, 'ann@example.com', 'Ann', 0, 1735787045);`,
    );
    // The script runs as it is on an empty database.
    const db = new DatabaseSync(path.join(dir, "dev.db"));
    db.exec(sql);
    expect(db.prepare("SELECT COUNT(*) AS n FROM posts").get()).toEqual({ n: 4 });
    db.close();
  });

  it("names a missing config", async () => {
    fs.rmSync(path.join(dir, "sizuku.config.ts"));
    await expect(seed(dir)).rejects.toThrow(/No sizuku\.config\.ts/u);
  });
});
